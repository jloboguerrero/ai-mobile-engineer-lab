#!/usr/bin/env bash
# PreToolUse hook (Edit|Write|MultiEdit).
# Blocks writes to native (CNG) / build output / secret paths. Exit 2 = block; stderr → model.
set -euo pipefail

input="$(cat)"
file_path="$(echo "$input" | jq -r '.tool_input.file_path // .tool_input.path // empty')"
[ -z "$file_path" ] && exit 0

rel="${file_path#"${CLAUDE_PROJECT_DIR:-$PWD}"/}"

block() { echo "Blocked: '$rel' — $1" >&2; exit 2; }

case "$rel" in
  ios/*|android/*|*/ios/*|*/android/*)
    block "native folders are generated by Continuous Native Generation (npx expo prebuild). Change app.json / app.config.ts or write a config plugin instead." ;;
  node_modules/*|*/node_modules/*|.expo/*|dist/*|coverage/*)
    block "build/dependency output, never edited." ;;
  package-lock.json|yarn.lock|pnpm-lock.yaml|bun.lockb)
    block "lockfile is managed by the package manager. Use npx expo install <pkg>." ;;
esac

if echo "$rel" | grep -qE '(^|/)\.env(\..*)?$|\.p8$|\.p12$|\.jks$|\.keystore$|\.mobileprovision$|google-services\.json$|GoogleService-Info\.plist$|credentials\.json$'; then
  block "secret/credential file. Ask the human to change it."
fi

# package.json: allow scripts edits, but dependencies must go through `npx expo install`.
if [ "$(basename "$rel")" = "package.json" ]; then
  new="$(echo "$input" | jq -r '.tool_input.new_string // .tool_input.content // empty')"
  if echo "$new" | grep -qE '"(dependencies|devDependencies)"|"[@a-z0-9./-]+"\s*:\s*"[~^]?[0-9]'; then
    block "don't add/bump dependencies by hand. Run 'npx expo install <pkg>' (or '-- --save-dev') so versions match the Expo SDK."
  fi
fi

exit 0
